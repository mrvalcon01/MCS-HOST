@IgnoreExtraProperties
data class ServerRoom(
    @DocumentId val id: String = "",
    val ownerUid: String = "",
    val staffUids: List<String> = emptyList(),
    val staffRoles: Map<String, String> = emptyMap(),
    val name: String = "My Minecraft Server",
    val motd: String = "Hosted free with MCS-HOST",
    val mode: String = ServerMode.LOCAL_BEDROCK.name,
    val edition: String = GameEdition.BEDROCK.name,
    val software: String = ServerSoftware.BEDROCK_HOST.name,
    val minecraftVersion: String = "1.21.50",
    val host: String = "0.0.0.0",
    val port: Long = 19132L,
    val seed: String = "CHERRY_VALLEY",
    val seedNumeric: Long = 1694827104L,
    val seedLabel: String = "Cherry Blossom Crater",
    val gamemode: String = GameModeOption.SURVIVAL.name,
    val difficulty: String = DifficultyOption.NORMAL.name,
    val maxPlayers: Long = 20L,
    val viewDistance: Long = 10L,
    val simulationDistance: Long = 6L,
    val pvp: Boolean = true,
    val hardcore: Boolean = false,
    val allowCheats: Boolean = false,
    val commandBlocks: Boolean = true,
    val onlineMode: Boolean = true,
    val whitelistEnabled: Boolean = false,
    val resourcePackRequired: Boolean = false,
    val keepInventory: Boolean = false,
    val mobGriefing: Boolean = true,
    val doDaylightCycle: Boolean = true,
    val doWeatherCycle: Boolean = true,
    val naturalRegeneration: Boolean = true,
    val operators: List<String> = emptyList(),
    val whitelist: List<String> = emptyList(),
    val bannedPlayers: List<String> = emptyList(),
    val inviteCode: String = "",
    val isPublicInDirectory: Boolean = false,
    val isOnline: Boolean = false,
    val playerCount: Long = 0L,
    @ServerTimestamp val createdAt: Timestamp? = null,
    @ServerTimestamp val updatedAt: Timestamp? = null
) {
    fun roleFor(uid: String): StaffRole {
        if (uid == ownerUid) return StaffRole.OWNER
        return when (staffRoles[uid]) {
            StaffRole.OWNER.name -> StaffRole.OWNER
            StaffRole.ADMIN.name -> StaffRole.ADMIN
            else -> StaffRole.MODERATOR
        }
    }

    fun isLocalHost(): Boolean = mode == ServerMode.LOCAL_BEDROCK.name
    fun softwareEnum(): ServerSoftware =
        ServerSoftware.entries.firstOrNull { it.name == software } ?: ServerSoftware.BEDROCK_HOST
    fun editionEnum(): GameEdition =
        GameEdition.entries.firstOrNull { it.name == edition } ?: GameEdition.BEDROCK
    fun gamemodeEnum(): GameModeOption =
        GameModeOption.entries.firstOrNull { it.name == gamemode } ?: GameModeOption.SURVIVAL
    fun difficultyEnum(): DifficultyOption =
        DifficultyOption.entries.firstOrNull { it.name == difficulty } ?: DifficultyOption.NORMAL

    fun toServerPropertiesText(): String = buildString {
        appendLine("# Generated by MCS-HOST (Free Open Server Manager)")
        appendLine("motd=$motd")
        appendLine("server-port=$port")
        appendLine("level-name=${name.lowercase().replace(Regex("[^a-z0-9_\\-]"), "_").ifBlank { "world" }}")
        appendLine("level-seed=$seedNumeric")
        appendLine("gamemode=${gamemodeEnum().commandValue}")
        appendLine("difficulty=${difficultyEnum().commandValue}")
        appendLine("max-players=$maxPlayers")
        appendLine("view-distance=$viewDistance")
        appendLine("simulation-distance=$simulationDistance")
        appendLine("pvp=$pvp")
        appendLine("hardcore=$hardcore")
        appendLine("allow-cheats=$allowCheats")
        appendLine("enable-command-block=$commandBlocks")
        appendLine("online-mode=$onlineMode")
        appendLine("white-list=$whitelistEnabled")
        appendLine("require-resource-pack=$resourcePackRequired")
    }
}

