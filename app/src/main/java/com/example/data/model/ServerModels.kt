    fun resolveNumericSeed(input: String): Long {
        val trimmed = input.trim()
        if (trimmed.isEmpty()) return 0L
        return trimmed.toLongOrNull() ?: javaHashCode64(trimmed)
    }

    private fun javaHashCode64(text: String): Long {
        var h = 0
        for (ch in text) {
            h = 31 * h + ch.code
        }
        return h.toLong()
    }
